import { readFileSync } from 'node:fs'
const read = (path) => readFileSync(path, 'utf8')
const checks = []
const assert = (name, condition) => checks.push({ name, pass: Boolean(condition) })
const focus = read('apps/web/src/features/focus/ProjectFocusNavigator.tsx')
const tools = read('apps/web/src/features/project/ProjectToolsDialog.tsx')
const searchIndex = read('apps/web/src/features/project/projectSearchIndex.ts')
const app = read('apps/web/src/App.tsx')
const client = read('apps/web/src/runtime/localCoreClient.ts')
assert('Focus is location-only', !focus.includes('artifactSearch') && !focus.includes('<input') && focus.includes('Object-first locator only'))
assert('Ctrl/Cmd+F opens Project Search', app.includes("setProjectToolsMode('search')"))
assert('F remains Selection Focus', app.includes("key === 'f' && selectedIds.length") && app.includes('openProjectFocus()'))
assert('Global search uses Local Core federated endpoint', client.includes('/search?${params.toString()}') && (tools.includes('props.client.projectSearch') || searchIndex.includes('input.client.projectSearch(')))
assert('Search hides engine choice', !tools.includes('语义</label>') && !tools.includes('vector distance') && !searchIndex.includes('vector distance'))
assert('Search includes Project Presentation entities', tools.includes('searchProjectFocusEntries') || searchIndex.includes('searchProjectFocusEntries'))
assert('Search result can hand off to Focus', tools.includes('onSelectSourceIds') || (app.includes('activateProjectSearchResult') && app.includes('openProjectFocus(item.sourceIds, item.title)')))
assert('Tap suppresses native context menu', app.includes("window.addEventListener('contextmenu', suppressContextMenu, true)"))
assert('Tap suppresses right-button browser default', app.includes("event.button === 2") && app.includes('suppressRightButtonDefault'))
assert('Editable controls keep native menu', app.includes('[data-native-context-menu="true"]') && app.includes('input, textarea, select'))
for (const check of checks) console.log(`${check.pass ? 'PASS' : 'FAIL'} ${check.name}`)
const failed = checks.filter((check) => !check.pass)
console.log(`\n${checks.length - failed.length}/${checks.length} R3.1A6 static contracts passed`)
if (failed.length) process.exit(1)
